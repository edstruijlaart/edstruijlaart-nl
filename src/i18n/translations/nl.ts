/**
 * Deep type that converts all leaf string literals to `string`
 * and readonly string[] to string[], so translations can have different values.
 */
type DeepStringify<T> = {
  -readonly [K in keyof T]: T[K] extends readonly (infer _U)[]
    ? readonly string[]
    : T[K] extends string
      ? string
      : T[K] extends object
        ? DeepStringify<T[K]>
        : T[K];
};

export type TranslationKeys = DeepStringify<typeof nl>;
